def circle(cx, cy, r): return f"M{cx-r},{cy} a{r},{r} 0 1,0 {2*r},0 a{r},{r} 0 1,0 {-2*r},0 z"
def ellipse(cx, cy, rx, ry): return f"M{cx-rx},{cy} a{rx},{ry} 0 1,0 {2*rx},0 a{rx},{ry} 0 1,0 {-2*rx},0 z"
def rrect(x, y, w, h, r):
    return (f"M{x+r},{y} h{w-2*r} a{r},{r} 0 0 1 {r},{r} v{h-2*r} a{r},{r} 0 0 1 {-r},{r} "
            f"h{-(w-2*r)} a{r},{r} 0 0 1 {-r},{-r} v{-(h-2*r)} a{r},{r} 0 0 1 {r},{-r} z")
def star(x, y, r): return f"M{x},{y-r} Q{x},{y} {x+r},{y} Q{x},{y} {x},{y+r} Q{x},{y} {x-r},{y} Q{x},{y} {x},{y-r} z"
def note(x, y, s):
    # note head (tilted ellipse approximated by rotating points), stem, flag
    pts = []
    for i in range(0, 361, 30):
        t = math.radians(i); a = math.radians(-20)
        px, py = 6 * math.cos(t), 4.6 * math.sin(t)
        pts.append((x + s * (px * math.cos(a) - py * math.sin(a)), y + s * (px * math.sin(a) + py * math.cos(a))))
    head = "M" + " L".join(f"{px:.2f},{py:.2f}" for px, py in pts) + " z"
    stem = rrect(x + s * 4.2, y - s * 22, s * 3, s * 22, s * 1.5)
    flag = f"M{x + s*7},{y - s*22} q{s*10},{s*3} {s*10},{s*13}"
    return head + " " + stem, flag

