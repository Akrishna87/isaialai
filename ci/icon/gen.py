PIVOT = 96

def vd_path(kind, d, color, alpha, width):
    a = f'android:fillAlpha="{alpha}"' if kind == "fill" else f'android:strokeAlpha="{alpha}"'
    if kind == "fill":
        return f'        <path android:fillColor="{color}" {a} android:pathData="{d}" />'
    return (f'        <path android:strokeColor="{color}" {a} android:strokeWidth="{width}" '
            f'android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{d}" />')

