# Adaptive icon: 108dp canvas, launcher shows the middle 72dp (scale 1.5), cropped by a mask.
def masked(clip):
    return (f'<svg viewBox="0 0 192 192" width="180" height="180"><defs><clipPath id="c{abs(hash(clip))}">{clip}</clipPath></defs>'
            f'<g clip-path="url(#c{abs(hash(clip))})"><g transform="translate(96 96) scale(1.5) translate(-96 -96)">{bg_svg}{svg_shapes()}</g></g></svg>')
