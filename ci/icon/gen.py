# SVG preview from the same shapes, shown in the masks launchers use.
def svg_shapes(scale=SCALE):
    out = [f'<g transform="translate({PIVOT} {PIVOT}) scale({scale}) translate({-PIVOT} {-PIVOT})">']
    for kind, d, color, alpha, width in shapes:
        if kind == "fill": out.append(f'<path d="{d}" fill="{color}" fill-opacity="{alpha}"/>')
        else: out.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-opacity="{alpha}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"/>')
    return "\n".join(out) + "</g>"
bg_svg = f'''<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#8E6BFF"/><stop offset="1" stop-color="#FF7A59"/></linearGradient>
<radialGradient id="r" cx="96" cy="88" r="84" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#fff" stop-opacity=".28"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient></defs>
<rect width="192" height="192" fill="url(#g)"/><path d="{circle(96,88,84)}" fill="url(#r)"/>'''
